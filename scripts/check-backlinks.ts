import assert from 'node:assert/strict';
import {createBacklinkQueue,type BacklinkState} from '../src/backlinks';
import type {BacklinkResponse} from '../src/types';

let next=0;
const timers=new Map<number,()=>void>();
const clock={set(fn:()=>void){const id=++next;timers.set(id,fn);return id},clear(id:number){timers.delete(id)}};
const advance=()=>{const jobs=[...timers.values()];timers.clear();for(const fn of jobs)fn()};
const flush=async()=>{for(let i=0;i<8;i++)await Promise.resolve()};
const flights:{id:string;resolve:(r:BacklinkResponse)=>void;reject:(e:Error)=>void}[]=[];
const states:BacklinkState[]=[];
const queue=createBacklinkQueue({request:id=>new Promise((resolve,reject)=>flights.push({id,resolve,reject})),show:s=>states.push(s),clock});
const result=(id:string,revision:number):BacklinkResponse=>({documentID:id,revision,status:'ready',items:[],total:0,truncated:false});
queue.context('a',1,false);advance();assert.equal(flights.length,0,'collapsed is lazy');
queue.visible(true);advance();assert.equal(flights.length,1);
queue.context('a',1,false);advance();assert.equal(flights.length,1,'position-only refresh ignored');
queue.context('b',2,false);advance();queue.context('c',3,false);advance();
flights[0].resolve(result('a',1));await flush();
assert.equal(states.filter(s=>s.kind==='ready').length,0,'old ID success rejected');
assert.equal(flights.length,2);assert.equal(flights[1].id,'c','single flight/newest job');
queue.context('c',4,false);advance();flights[1].reject(Error('old revision'));await flush();
assert.notEqual(states.at(-1)?.kind,'error');assert.equal(flights.length,3);
flights[2].resolve(result('c',3));await flush();
assert.notEqual(states.at(-1)?.kind,'ready','response revision validated');
queue.refresh();advance();flights[3].resolve(result('c',4));await flush();assert.equal(states.at(-1)?.kind,'ready');
queue.context('c',4,true);advance();assert.equal(flights.length,4);assert.equal(states.at(-1)?.kind,'paused');
queue.context('c',5,false);advance();queue.context('c',5,true);
flights[4].resolve(result('c',5));await flush();assert.equal(states.at(-1)?.kind,'paused','pending/IME discards old response');
queue.context('c',5,false);advance();queue.language();advance();
flights[5].reject(Error('old locale'));await flush();assert.equal(flights.length,7);
queue.visible(false);flights[6].resolve(result('c',5));await flush();assert.notEqual(states.at(-1)?.kind,'ready','closed ignores response');
queue.visible(true);advance();flights[7].reject(Error('unavailable'));await flush();assert.equal(states.at(-1)?.kind,'error');
queue.retry();advance();flights[8].resolve(result('c',5));await flush();assert.equal(states.at(-1)?.kind,'ready');
queue.dispose();queue.refresh();advance();assert.equal(flights.length,9);
console.log('PASS: lazy backlinks, one flight/newest pending, ID/revision/locale/close invalidation, pending/IME and retry');
