// Generate the PDF text-layer radical mappings on macOS.
// Usage: swift scripts/gen-pdf-radicals.swift > pdf_radicals.go
// Or compile with swiftc and run the resulting binary.
import Foundation
import CoreText

func compatibilityIdeograph(_ code: UInt32) -> UInt32? {
    let normalized = String(UnicodeScalar(code)!).precomposedStringWithCompatibilityMapping
    let scalars = Array(normalized.unicodeScalars)
    guard scalars.count == 1, scalars[0].value != code else { return nil }
    return scalars[0].value
}

func glyph(_ font: CTFont, _ code: UInt32) -> CGGlyph? {
    var character = UniChar(code)
    var result: CGGlyph = 0
    guard CTFontGetGlyphsForCharacters(font, &character, &result, 1), result != 0 else { return nil }
    return result
}

let fontNames = ["PingFang SC", "Hiragino Sans GB", "Songti SC", "Heiti SC", "Kaiti SC"]
let fonts = fontNames.map { CTFontCreateWithName($0 as CFString, 12, nil) }
// Ascending scans, with the main unified block taking priority over Extension A.
let glyphIdeographs: [[CGGlyph: UInt32]] = fonts.map { font in
    var matches: [CGGlyph: UInt32] = [:]
    for block in [UInt32(0x4E00)...UInt32(0x9FFF), UInt32(0x3400)...UInt32(0x4DBF)] {
        for code in block {
            if let g = glyph(font, code), matches[g] == nil { matches[g] = code }
        }
    }
    return matches
}
var mappings: [UInt32: UInt32] = [:]
var kangxiCount = 0
var supplementCount = 0
var supplementNFKCCount = 0
for code in UInt32(0x2F00)...UInt32(0x2FD5) {
    guard let target = compatibilityIdeograph(code) else {
        fatalError(String(format: "Missing Kangxi compatibility mapping U+%04X", code))
    }
    mappings[code] = target
    kangxiCount += 1
}
for code in UInt32(0x2E80)...UInt32(0x2EF3) {
    if let target = compatibilityIdeograph(code) {
        mappings[code] = target
        supplementCount += 1
        supplementNFKCCount += 1
        continue
    }
    for (index, font) in fonts.enumerated() {
        if let g = glyph(font, code), let target = glyphIdeographs[index][g] {
            mappings[code] = target
            supplementCount += 1
            break
        }
    }
}
print("// Code generated by scripts/gen-pdf-radicals.swift; DO NOT EDIT.")
print("\npackage main\n")
print("var pdfRadicalIdeographs = map[rune]rune{")
for code in mappings.keys.sorted() {
    let target = mappings[code]!
    print(String(format: "\t0x%04X: 0x%04X, // %@ → %@", code, target,
                 String(UnicodeScalar(code)!), String(UnicodeScalar(target)!)))
}
print("}")
let summary = "Kangxi Radicals: \(kangxiCount); CJK Radicals Supplement: \(supplementCount) (NFKC: \(supplementNFKCCount), glyph: \(supplementCount - supplementNFKCCount)); total: \(mappings.count)\n"
FileHandle.standardError.write(Data(summary.utf8))
