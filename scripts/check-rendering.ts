import assert from 'node:assert/strict';
import {EditorState} from '@codemirror/state';
import {markdown,markdownLanguage} from '@codemirror/lang-markdown';
import {ensureSyntaxTree} from '@codemirror/language';
import {GFM} from '@lezer/markdown';
import {createBlockField,inlineDecorations,composing,setComposing} from '../src/editor';
const field=createBlockField(async()=> 'data:image/png;base64,');
let state=EditorState.create({doc:'# 标题\n\n正文 [链接](https://example.com)\n\n- [ ] 待办\n\n| 项目 | 说明 |\n| --- | --- |\n| 甲 | 乙 |\n\n![图](<图片 目录/a.png>)\n',extensions:[markdown({base:markdownLanguage,extensions:GFM}),composing,field]});
ensureSyntaxTree(state,state.doc.length,5000);state=state.update({}).state;
const collect=(set:any)=>{const out:any[]=[];set.between(0,state.doc.length,(from:number,to:number,value:any)=>{out.push({from,to,value})});return out};
const blocks=collect(state.field(field)),inline=collect(inlineDecorations(state,[{from:0,to:state.doc.length}]));
assert.ok(blocks.some(x=>x.value.spec.widget?.constructor.name==='TableWidget'));
assert.ok(blocks.some(x=>x.value.spec.widget?.constructor.name==='ImageWidget'&&x.value.spec.widget.dest==='图片 目录/a.png'));
assert.ok(inline.some(x=>x.value.spec.widget?.constructor.name==='TaskWidget'));
assert.ok(inline.some(x=>x.value.spec.attributes?.['data-href']==='https://example.com'));
assert.ok(inline.every(x=>!blocks.some(b=>x.from>=b.from&&x.from<b.to)),'block widgets own their contents');
const taskLine=state.doc.line(5);
const visible=collect(inlineDecorations(state,[{from:taskLine.from,to:taskLine.to}]));
assert.ok(visible.some(x=>x.value.spec.widget?.constructor.name==='TaskWidget'));
assert.ok(visible.every(x=>x.from>=taskLine.from&&x.to<=taskLine.to),'offscreen nodes have no decorations');
const before=state.field(field);state=state.update({}).state;
assert.equal(state.field(field),before,'idle transactions reuse block decorations');
state=state.update({effects:setComposing.of(true)}).state;
assert.equal(state.field(composing),true);
assert.equal(state.field(field),before,'composition keeps decorations');
state=state.update({changes:{from:state.doc.length,insert:'拼'}}).state;
assert.equal(state.field(composing),true);assert.ok(state.doc.toString().endsWith('拼'));
state=state.update({changes:{from:0,insert:'拼'}}).state;
assert.equal(state.field(composing),true);assert.ok(state.doc.toString().startsWith('拼'));
const mapped=collect(state.field(field));
assert.equal(mapped.length,blocks.length);
assert.equal(mapped[0].from,blocks[0].from+1,'composition maps block positions');
state=state.update({effects:setComposing.of(false)}).state;assert.equal(state.field(composing),false);
const imageFrom=state.doc.toString().indexOf('![图]');
state=state.update({selection:{anchor:imageFrom+3}}).state;
assert.ok(!collect(state.field(field)).some(x=>x.value.spec.widget?.constructor.name==='ImageWidget'),'selected image reveals source');
const tableFrom=state.doc.toString().indexOf('| 项目');
state=state.update({selection:{anchor:tableFrom+2}}).state;
assert.ok(!collect(state.field(field)).some(x=>x.value.spec.widget?.constructor.name==='TableWidget'),'selected table reveals source');

state=EditorState.create({doc:'光标\n\n## 标题 **粗体**\n\n> 引用\n> 下一行\n\n```ts\nconst x=1\n```\n\n[链接](<文件 目录/a\\(1\\).md>)\n\n![图](<图片 目录/a\\(1\\).png>)\n\n内联 ![小图](a.png) 文字\n',extensions:[markdown({base:markdownLanguage,extensions:GFM}),composing,field]});
ensureSyntaxTree(state,state.doc.length,5000);state=state.update({}).state;
const styled=collect(inlineDecorations(state,[{from:0,to:state.doc.length}]));
assert.ok(styled.some(x=>x.value.spec.class==='md-heading md-h2'));
assert.equal(styled.filter(x=>x.value.spec.class==='md-quote').length,2);
assert.equal(styled.filter(x=>x.value.spec.class==='md-code-line').length,3);
assert.ok(styled.some(x=>x.value.spec.attributes?.['data-href']==='文件 目录/a(1).md'));
assert.ok(collect(state.field(field)).some(x=>x.value.spec.widget?.dest==='图片 目录/a(1).png'));
assert.equal(collect(state.field(field)).filter(x=>x.value.spec.widget?.constructor.name==='ImageWidget').length,1,'inline images remain source');
const codeLine=state.doc.line(9);
assert.equal(collect(inlineDecorations(state,[{from:codeLine.from,to:codeLine.to}])).filter(x=>x.value.spec.class==='md-code-line').length,1,'multiline classes stay in viewport');
console.log('任务与表格装饰、中文组合输入期间保留文本和暂停排版检查通过');
